	@Override
	public void setupAnim(CrystalLurkerRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float pos = state.walkAnimationPos;
		float speed = Math.min(state.walkAnimationSpeed, 1.0f);
		float awake = 1.0f - state.dormant;
		head.yRot += Mth.clamp(state.yRot, -40.0f, 40.0f) * Mth.DEG_TO_RAD * awake;
		head.xRot += state.xRot * Mth.DEG_TO_RAD * 0.5f * awake;

		// heavy gait
		rLeg.xRot += Mth.cos(pos * 0.6f) * 0.7f * speed;
		lLeg.xRot -= Mth.cos(pos * 0.6f) * 0.7f * speed;
		rArm.xRot -= Mth.cos(pos * 0.6f) * 0.45f * speed;
		lArm.xRot += Mth.cos(pos * 0.6f) * 0.45f * speed;
		body.zRot += Mth.sin(pos * 0.6f) * 0.05f * speed;
		body.y += Mth.sin(age * 0.05f) * 0.4f * awake;

		if (state.slam > 0.0f) {
			poseSlam(Mth.sin(state.slam * Mth.PI));
		}

		if (state.dormant > 0.0f) {
			poseDormant(state.dormant);
		}
	}

	private void poseDormant(float k) {
		body.y += k * 9.000f;
		body.xRot += k * 0.750f;
		head.xRot += k * 0.600f;
		head.y += k * 2.000f;
		rArm.xRot += k * -0.600f;
		rArm.zRot += k * 0.300f;
		lArm.xRot += k * -0.600f;
		lArm.zRot += k * -0.300f;
		rForearm.xRot += k * -1.200f;
		lForearm.xRot += k * -1.200f;
		rLeg.xRot += k * -1.300f;
		rLeg.y += k * 6.000f;
		lLeg.xRot += k * -1.300f;
		lLeg.y += k * 6.000f;
		rFoot.xRot += k * 1.300f;
		lFoot.xRot += k * 1.300f;
	}

	private void poseSlam(float k) {
		rArm.xRot += k * -2.300f;
		lArm.xRot += k * -2.300f;
		rForearm.xRot += k * -0.400f;
		lForearm.xRot += k * -0.400f;
		body.xRot += k * -0.200f;
	}


