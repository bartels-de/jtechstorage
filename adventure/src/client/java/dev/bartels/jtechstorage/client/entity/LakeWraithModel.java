	@Override
	public void setupAnim(LakeWraithRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float speed = Math.min(state.walkAnimationSpeed, 1.0f);
		body.y += Mth.sin(age * 0.08f) * 2.5f;
		body.xRot += speed * 0.3f;
		ModelPart[] tentacles = {t0, t1, t2, t3, t4, t5};
		ModelPart[] tips = {t0Tip, t1Tip, t2Tip, t3Tip, t4Tip, t5Tip};

		for (int k = 0; k < 6; k++) {
			tentacles[k].xRot += Mth.sin(age * 0.12f + k) * 0.25f;
			tentacles[k].zRot += Mth.cos(age * 0.1f + k) * 0.2f;
			tips[k].xRot += Mth.sin(age * 0.12f + k - 0.8f) * 0.35f;
		}

		rArm.xRot += Mth.sin(age * 0.09f) * 0.2f;
		lArm.xRot += Mth.sin(age * 0.09f + 1.0f) * 0.2f;

		if (state.grab > 0.0f) {
			poseGrab(Mth.sin(state.grab * Mth.PI));
		}
	}

	private void poseGrab(float k) {
		rArm.xRot += k * -1.300f;
		rArm.zRot += k * -0.300f;
		lArm.xRot += k * -1.300f;
		lArm.zRot += k * 0.300f;
		body.xRot += k * 0.300f;
	}


