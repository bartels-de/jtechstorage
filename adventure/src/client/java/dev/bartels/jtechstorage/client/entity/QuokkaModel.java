	@Override
	public void setupAnim(QuokkaRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float pos = state.walkAnimationPos;
		float speed = Math.min(state.walkAnimationSpeed, 1.0f);
		head.yRot += Mth.clamp(state.yRot, -40.0f, 40.0f) * Mth.DEG_TO_RAD;
		head.xRot += state.xRot * Mth.DEG_TO_RAD * 0.5f;

		// hopping gait: both hind legs together, the body bobs
		float hopWalk = Math.max(0.0f, Mth.sin(pos * 0.9f)) * speed;
		quokka.y -= hopWalk * 3.0f;
		rLeg.xRot += Mth.cos(pos * 0.9f) * 0.8f * speed;
		lLeg.xRot += Mth.cos(pos * 0.9f) * 0.8f * speed;
		rArm.xRot += Mth.sin(pos * 0.9f) * 0.4f * speed;
		lArm.xRot += Mth.sin(pos * 0.9f) * 0.4f * speed;
		tail.xRot += Mth.sin(pos * 0.9f) * 0.2f * speed + Mth.sin(age * 0.08f) * 0.05f;
		rEar.zRot += Mth.sin(age * 0.11f) * 0.08f;
		lEar.zRot -= Mth.sin(age * 0.13f + 1.0f) * 0.08f;

		if (state.sitting) {
			poseSit(1.0f);
		}

		if (state.hop > 0.0f) {
			poseHop(Mth.sin(state.hop * Mth.PI));
		}
	}

	private void poseSit(float k) {
		quokka.y += k * 3.000f;
		body.xRot += k * 0.250f;
		rLeg.xRot += k * -1.200f;
		rLeg.y += k * 1.000f;
		lLeg.xRot += k * -1.200f;
		lLeg.y += k * 1.000f;
		rFoot.xRot += k * 1.200f;
		lFoot.xRot += k * 1.200f;
		tail.xRot += k * 0.600f;
		head.xRot += k * -0.250f;
	}

	private void poseHop(float k) {
		quokka.y += k * -5.000f;
		rArm.xRot += k * -2.200f;
		lArm.xRot += k * -2.200f;
		rEar.zRot += k * -0.400f;
		lEar.zRot += k * 0.400f;
		rLeg.xRot += k * 0.600f;
		lLeg.xRot += k * 0.600f;
		head.xRot += k * -0.300f;
	}


