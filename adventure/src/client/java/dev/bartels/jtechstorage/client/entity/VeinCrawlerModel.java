	@Override
	public void setupAnim(VeinCrawlerRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float pos = state.walkAnimationPos;
		float speed = Math.min(state.walkAnimationSpeed, 1.0f);
		head.yRot += Mth.clamp(state.yRot, -40.0f, 40.0f) * Mth.DEG_TO_RAD;
		head.xRot += state.xRot * Mth.DEG_TO_RAD * 0.5f;

		// tripod gait: front right, middle left, rear right together
		float a = Mth.cos(pos * 1.2f) * 0.5f * speed;
		float lift = Mth.sin(pos * 1.2f) * 0.3f * speed;
		rfLeg.yRot += a;
		lmLeg.yRot += a;
		rhLeg.yRot += a;
		lfLeg.yRot -= a;
		rmLeg.yRot -= a;
		lhLeg.yRot -= a;
		rfLeg.zRot += Math.max(0.0f, lift);
		rhLeg.zRot += Math.max(0.0f, lift);
		lmLeg.zRot -= Math.max(0.0f, lift);
		lfLeg.zRot -= Math.max(0.0f, -lift);
		lhLeg.zRot -= Math.max(0.0f, -lift);
		rmLeg.zRot += Math.max(0.0f, -lift);
		tail.yRot += Mth.sin(age * 0.1f) * 0.2f + Mth.cos(pos * 1.2f) * 0.3f * speed;
		tailTip.yRot += Mth.sin(age * 0.1f - 0.7f) * 0.3f;
		jaw.xRot += Math.max(0.0f, Mth.sin(age * 0.07f)) * 0.08f;

		if (state.spit > 0.0f) {
			poseSpit(Mth.sin(state.spit * Mth.PI));
		}
	}

	private void poseSpit(float k) {
		head.xRot += k * -0.450f;
		jaw.xRot += k * 0.900f;
		body.xRot += k * -0.100f;
	}


