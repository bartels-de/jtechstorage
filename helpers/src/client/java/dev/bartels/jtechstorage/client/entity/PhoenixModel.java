	@Override
	public void setupAnim(PhoenixRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		lids.visible = state.resting && !state.flying;

		if (state.resting && !state.flying) {
			poseSleep(1.0f);
			float breath = Mth.sin(age * 0.06f);
			body.y += breath * 0.3f;
			tail.xRot += breath * 0.03f;
			return;
		}

		head.yRot += state.yRot * Mth.DEG_TO_RAD * 0.7f;
		head.xRot += state.xRot * Mth.DEG_TO_RAD * 0.5f;
		crest.xRot += Mth.sin(age * 0.11f) * 0.06f;
		streamerR.yRot += Mth.sin(age * 0.13f) * 0.12f;
		streamerL.yRot -= Mth.sin(age * 0.13f + 0.5f) * 0.12f;

		if (state.flying) {
			poseFly(1.0f);
			float flap = Mth.sin(age * 0.55f);
			poseFlap(flap);
			rWingTip.zRot += Mth.sin(age * 0.55f - 0.7f) * 0.25f;
			lWingTip.zRot -= Mth.sin(age * 0.55f - 0.7f) * 0.25f;
			body.xRot += Mth.sin(age * 0.55f + 1.0f) * 0.04f;
			body.y += -flap * 0.6f;
			tail.xRot += Mth.sin(age * 0.3f) * 0.08f;
		} else {
			// sitting: head nodding, tail bobbing, wings breathing
			neck.xRot += Mth.sin(age * 0.08f) * 0.06f;
			tail.xRot += Mth.sin(age * 0.05f) * 0.05f;
			float breathe = Mth.sin(age * 0.07f) * 0.03f;
			rWing.zRot += breathe;
			lWing.zRot -= breathe;
		}
	}

	private void poseFly(float k) {
		body.xRot += k * 0.300f;
		rWing.xRot += k * 1.720f;
		rWing.zRot += k * -1.450f;
		lWing.xRot += k * 1.720f;
		lWing.zRot += k * 1.450f;
		rWingTip.xRot += k * -0.100f;
		rWingTip.yRot += k * -0.100f;
		lWingTip.xRot += k * -0.100f;
		lWingTip.yRot += k * 0.100f;
		neck.xRot += k * 0.350f;
		head.xRot += k * -0.300f;
		tail.xRot += k * -0.450f;
		tail0.yRot += k * -0.250f;
		tail1.yRot += k * -0.120f;
		tail3.yRot += k * 0.120f;
		tail4.yRot += k * 0.250f;
		rLeg.xRot += k * 1.100f;
		lLeg.xRot += k * 1.100f;
	}

	private void poseFlap(float k) {
		rWing.zRot += k * 0.650f;
		lWing.zRot += k * -0.650f;
		rWingTip.zRot += k * 0.350f;
		lWingTip.zRot += k * -0.350f;
	}

	private void poseSleep(float k) {
		body.y += k * 1.900f;
		body.xRot += k * 0.150f;
		neck.xRot += k * 0.950f;
		neck.yRot += k * 1.200f;
		head.xRot += k * 0.300f;
		head.yRot += k * 1.500f;
		crest.xRot += k * 0.400f;
		tail.xRot += k * 0.250f;
		rLeg.xRot += k * -0.300f;
		lLeg.xRot += k * -0.300f;
		rWing.zRot += k * 0.080f;
		lWing.zRot += k * -0.080f;
	}

	@Override
	public void translateToHat(PoseStack pose) {
		root().translateAndRotate(pose);
		phoenix.translateAndRotate(pose);
		body.translateAndRotate(pose);
		neck.translateAndRotate(pose);
		head.translateAndRotate(pose);
		pose.translate(0.0f, 0.0f, -1.5f / 16.0f);
	}

