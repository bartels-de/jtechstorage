package dev.bartels.jtechstorage.client.cosmetic;

import net.minecraft.client.renderer.entity.state.AvatarRenderState;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.util.Mth;

import dev.bartels.jtechstorage.JTechStorage;

/**
 * Shoulder sprite: a small amethyst sprite hovering above the right shoulder.
 * Model at double detail density (half pixels) – the renderer scales it to 0.5.
 * Generated by scratchpad/cosmetics.py (parts and poses), animation written by hand.
 */
public class ShoulderSpriteModel extends EntityModel<AvatarRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(JTechStorage.id("cosmetic_shoulder_sprite"), "main");

	private final ModelPart sprite;
	private final ModelPart core;
	private final ModelPart rWing;
	private final ModelPart lWing;

	public ShoulderSpriteModel(ModelPart root) {
		super(root);
		this.sprite = root.getChild("sprite");
		this.core = root.getChild("sprite").getChild("core");
		this.rWing = root.getChild("sprite").getChild("core").getChild("r_wing");
		this.lWing = root.getChild("sprite").getChild("core").getChild("l_wing");
	}

	public static LayerDefinition createBodyLayer() {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
		PartDefinition p1 = root.addOrReplaceChild("sprite", CubeListBuilder.create(),
				PartPose.offset(-15.0f, -12.0f, 3.0f));
		PartDefinition p2 = p1.addOrReplaceChild("core", CubeListBuilder.create()
				.texOffs(34, 0).addBox(-1.5f, 0.0f, -1.5f, 3.0f, 5.0f, 3.0f, new CubeDeformation(0.0f))
				.texOffs(14, 0).addBox(-2.5f, -5.0f, -2.5f, 5.0f, 5.0f, 5.0f, new CubeDeformation(0.0f))
				.texOffs(46, 0).addBox(-2.0f, -7.0f, 0.0f, 1.0f, 3.0f, 1.0f, new CubeDeformation(0.0f))
				.texOffs(46, 0).addBox(1.0f, -7.0f, 0.0f, 1.0f, 3.0f, 1.0f, new CubeDeformation(0.0f)),
				PartPose.ZERO);
		p2.addOrReplaceChild("r_wing", CubeListBuilder.create()
				.texOffs(0, 0).addBox(-0.5f, -6.0f, 0.0f, 1.0f, 7.0f, 6.0f, new CubeDeformation(0.0f)),
				PartPose.offsetAndRotation(-1.5f, 1.0f, 1.0f, 0.0f, -0.5f, -0.3f));
		p2.addOrReplaceChild("l_wing", CubeListBuilder.create()
				.texOffs(0, 0).addBox(-0.5f, -6.0f, 0.0f, 1.0f, 7.0f, 6.0f, new CubeDeformation(0.0f)),
				PartPose.offsetAndRotation(1.5f, 1.0f, 1.0f, 0.0f, 0.5f, 0.3f));
		return LayerDefinition.create(mesh, 64, 64);
	}

	@Override
	public void setupAnim(AvatarRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		sprite.y += Mth.sin(age * 0.13f) * 1.6f;
		sprite.x += Mth.sin(age * 0.05f) * 0.8f;
		core.yRot += Mth.sin(age * 0.04f) * 0.4f + 0.5f;
		rWing.yRot += Mth.sin(age * 1.3f) * 0.55f;
		lWing.yRot -= Mth.sin(age * 1.3f) * 0.55f;
	}




}
