	@Override
	public void setupAnim(AvatarRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float speed = Math.min(state.walkAnimationSpeed, 1.0f);
		float flap = Mth.sin(age * (0.07f + speed * 0.22f)) * (0.05f + speed * 0.16f);

		if (state.isFallFlying) {
			flap = Mth.sin(age * 0.55f) * 0.3f;
		}

		rWing.yRot -= flap;
		lWing.yRot += flap;
		rWing.zRot -= flap * 0.35f;
		lWing.zRot += flap * 0.35f;

		if (state.isCrouching) {
			rWing.yRot -= 0.4f;
			lWing.yRot += 0.4f;
			wings.y += 2.0f;
		}
	}




