package dev.bartels.jtechstorage.client.cosmetic;

import net.minecraft.client.renderer.entity.state.AvatarRenderState;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.util.Mth;

import dev.bartels.jtechstorage.JTechStorage;

/**
 * Resonance mushroom hat: a small glowing mushroom that bobs while walking.
 * Model at double detail density (half pixels) – the renderer scales it to 0.5.
 * Generated by scratchpad/cosmetics.py (parts and poses), animation written by hand.
 */
public class ShroomHatModel extends EntityModel<AvatarRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(JTechStorage.id("cosmetic_shroom_hat"), "main");

	private final ModelPart shroom;
	private final ModelPart cap;

	public ShroomHatModel(ModelPart root) {
		super(root);
		this.shroom = root.getChild("shroom");
		this.cap = root.getChild("shroom").getChild("cap");
	}

	public static LayerDefinition createBodyLayer() {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
		PartDefinition p1 = root.addOrReplaceChild("shroom", CubeListBuilder.create()
				.texOffs(40, 17).addBox(-2.0f, -6.0f, -2.0f, 4.0f, 6.0f, 4.0f, new CubeDeformation(0.0f)),
				PartPose.offsetAndRotation(2.0f, -16.0f, -1.0f, 0.0f, 0.3f, 0.12f));
		p1.addOrReplaceChild("cap", CubeListBuilder.create()
				.texOffs(0, 0).addBox(-7.0f, -3.0f, -7.0f, 14.0f, 3.0f, 14.0f, new CubeDeformation(0.0f))
				.texOffs(0, 17).addBox(-5.0f, -5.0f, -5.0f, 10.0f, 2.0f, 10.0f, new CubeDeformation(0.0f))
				.texOffs(0, 29).addBox(-3.0f, -6.0f, -3.0f, 6.0f, 1.0f, 6.0f, new CubeDeformation(0.0f))
				.texOffs(28, 29).addBox(-5.0f, -4.0f, -2.0f, 2.0f, 1.0f, 2.0f, new CubeDeformation(0.0f))
				.texOffs(28, 29).addBox(2.0f, -5.5f, 1.0f, 2.0f, 1.0f, 2.0f, new CubeDeformation(0.0f))
				.texOffs(24, 29).addBox(4.0f, -6.0f, -4.0f, 1.0f, 3.0f, 1.0f, new CubeDeformation(0.0f)),
				PartPose.offset(0.0f, -6.0f, 0.0f));
		return LayerDefinition.create(mesh, 64, 64);
	}

	@Override
	public void setupAnim(AvatarRenderState state) {
		super.setupAnim(state);
		float speed = Math.min(state.walkAnimationSpeed, 1.0f);
		shroom.zRot += Mth.sin(state.walkAnimationPos * 0.66f) * 0.18f * speed + Mth.sin(state.ageInTicks * 0.05f) * 0.03f;
		shroom.xRot += Mth.cos(state.walkAnimationPos * 0.66f) * 0.08f * speed;
		cap.yRot += Mth.sin(state.ageInTicks * 0.03f) * 0.12f;
	}




}
