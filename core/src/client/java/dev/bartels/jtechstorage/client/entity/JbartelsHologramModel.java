	@Override
	public void setupAnim(JbartelsHologramRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		base.yRot = age * 0.04f;
		jbartels.y += Mth.sin(age * 0.08f) * 0.6f - 0.6f;

		if (state.standby) {
			poseStandby(1.0f);
			head.xRot += Mth.sin(age * 0.05f) * 0.04f;
			return;
		}

		head.yRot = state.yRot * Mth.DEG_TO_RAD;
		head.xRot = state.xRot * Mth.DEG_TO_RAD + Mth.sin(age * 0.25f) * 0.04f;
		coat.xRot += Mth.sin(age * 0.06f) * 0.04f;

		// cycle (20 s): explain – tablet – explain – wave
		float cycle = (age % 400.0f) / 400.0f;
		float tablet = window(cycle, 0.30f, 0.50f);
		float wave = window(cycle, 0.80f, 0.92f);
		float explain = Math.max(0.0f, 1.0f - tablet - wave);
		poseExplain(explain);
		poseTablet(tablet);
		poseWave(wave);
		rArm.xRot += Mth.sin(age * 0.18f) * 0.3f * explain;
		rArm.zRot += Mth.sin(age * 0.11f) * 0.1f * explain;
		rFore.xRot += Mth.sin(age * 0.23f) * 0.2f * explain;
		rFore.xRot += Mth.sin(age * 1.2f) * 0.06f * tablet;      // taps
		rFore.zRot += Mth.sin(age * 0.6f) * 0.35f * wave;        // waves
	}

	private void poseExplain(float k) {
		rArm.xRot += k * -0.750f;
		rArm.zRot += k * 0.150f;
		rFore.xRot += k * -0.700f;
		lArm.xRot += k * -0.300f;
		lArm.zRot += k * -0.100f;
		lFore.xRot += k * -0.600f;
	}

	private void poseTablet(float k) {
		lArm.xRot += k * -0.350f;
		lArm.zRot += k * -0.050f;
		lFore.xRot += k * -0.750f;
		rArm.xRot += k * -0.450f;
		rArm.yRot += k * -0.300f;
		rArm.zRot += k * -0.250f;
		rFore.xRot += k * -0.850f;
		head.xRot += k * 0.450f;
	}

	private void poseWave(float k) {
		rArm.xRot += k * -0.300f;
		rArm.zRot += k * 2.350f;
		rFore.zRot += k * 0.400f;
		head.zRot += k * 0.080f;
		lArm.xRot += k * -0.300f;
		lFore.xRot += k * -0.600f;
	}

	private void poseStandby(float k) {
		head.xRot += k * 0.550f;
		body.xRot += k * 0.080f;
		rArm.xRot += k * 0.100f;
		rArm.zRot += k * 0.050f;
		lArm.xRot += k * -0.250f;
		lFore.xRot += k * -0.500f;
	}

	/** Smooth fade in/out of a time window (0..1). */
	private static float window(float t, float from, float to) {
		float edge = 0.04f;
		if (t < from - edge || t > to + edge) {
			return 0.0f;
		}
		float in = Mth.clamp((t - (from - edge)) / edge, 0.0f, 1.0f);
		float out = Mth.clamp(((to + edge) - t) / edge, 0.0f, 1.0f);
		return Math.min(in, out);
	}

	@Override
	public void translateToHand(JbartelsHologramRenderState state, HumanoidArm arm, PoseStack pose) {
		root().translateAndRotate(pose);
		jbartels.translateAndRotate(pose);
		body.translateAndRotate(pose);
		rArm.translateAndRotate(pose);
		rFore.translateAndRotate(pose);
		pose.translate(0.0f, -9.0f / 16.0f, 0.0f);
		pose.scale(2.0f, 2.0f, 2.0f);
	}
